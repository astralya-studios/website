/**
 * Order store — file-based for v1.
 *
 * Orders live as JSON files under `data/orders/`. The exported functions are
 * the store's interface; swapping in Postgres/Supabase/etc. later means
 * reimplementing these functions, not touching call sites.
 *
 * Inventory: content JSON holds the starting stock per sign. Runtime
 * decrements are tracked as overrides in `data/inventory.json` so content
 * files stay clean.
 */

import { promises as fs } from "fs";
import path from "path";
import type { PaymentMode } from "./payments";
import { getSign } from "./catalog";

export { shippingFor } from "./pricing";

const DATA_DIR = path.join(process.cwd(), "data");
const ORDERS_DIR = path.join(DATA_DIR, "orders");
const INVENTORY_FILE = path.join(DATA_DIR, "inventory.json");

export interface OrderItem {
  signId: string;
  name: string;
  qty: number;
  unitPrice: number;
}

export interface ShippingAddress {
  name: string;
  address1: string;
  address2?: string;
  city: string;
  region: string;
  postalCode: string;
  country: string;
}

export type OrderStatus = "pending" | "paid" | "cancelled";

export interface Order {
  id: string;
  status: OrderStatus;
  items: OrderItem[];
  subtotal: number;
  shipping: number;
  total: number;
  currency: string;
  customer: { name: string; email: string };
  shippingAddress: ShippingAddress;
  payment: { driver: string; mode: PaymentMode; sessionId: string | null };
  createdAt: string;
  paidAt: string | null;
}

async function ensureDirs() {
  await fs.mkdir(ORDERS_DIR, { recursive: true });
}

function orderPath(id: string) {
  // IDs are generated by us (AST-…), but sanitize anyway.
  const safe = id.replace(/[^A-Za-z0-9-]/g, "");
  return path.join(ORDERS_DIR, `${safe}.json`);
}

export function generateOrderId(): string {
  const date = new Date().toISOString().slice(0, 10).replace(/-/g, "");
  const rand = Math.random().toString(36).slice(2, 6).toUpperCase();
  return `AST-${date}-${rand}`;
}

export async function createOrder(
  order: Omit<Order, "id" | "createdAt" | "paidAt" | "status">
): Promise<Order> {
  await ensureDirs();
  const full: Order = {
    ...order,
    id: generateOrderId(),
    status: "pending",
    createdAt: new Date().toISOString(),
    paidAt: null,
  };
  await fs.writeFile(orderPath(full.id), JSON.stringify(full, null, 2));
  return full;
}

export async function getOrder(id: string): Promise<Order | null> {
  try {
    const raw = await fs.readFile(orderPath(id), "utf-8");
    return JSON.parse(raw) as Order;
  } catch {
    return null;
  }
}

export async function updateOrder(
  id: string,
  patch: Partial<Pick<Order, "status" | "paidAt" | "payment">>
): Promise<Order | null> {
  const order = await getOrder(id);
  if (!order) return null;
  const updated: Order = { ...order, ...patch };
  await fs.writeFile(orderPath(id), JSON.stringify(updated, null, 2));
  return updated;
}

/**
 * Mark an order paid and decrement inventory for in-stock items.
 * Called by the Stripe webhook and by the dev-mode confirmation —
 * the single place where payment completion is recorded.
 */
export async function markOrderPaid(id: string): Promise<Order | null> {
  const order = await getOrder(id);
  if (!order || order.status !== "pending") return order;
  for (const item of order.items) {
    const sign = getSign(item.signId);
    if (sign && sign.status === "available") {
      await decrementInventory(item.signId, item.qty);
    }
  }
  return updateOrder(id, {
    status: "paid",
    paidAt: new Date().toISOString(),
  });
}

/* ---------------- Inventory overrides ---------------- */

async function readOverrides(): Promise<Record<string, number>> {
  try {
    const raw = await fs.readFile(INVENTORY_FILE, "utf-8");
    return JSON.parse(raw) as Record<string, number>;
  } catch {
    return {};
  }
}

/**
 * Units remaining for a sign: runtime override if present, else the
 * content file's starting stock. null = not tracked (unlimited / TBD).
 */
export async function getRemaining(signId: string): Promise<number | null> {
  const sign = getSign(signId);
  if (!sign) return null;
  const overrides = await readOverrides();
  if (signId in overrides) return overrides[signId];
  return sign.inventory;
}

export async function decrementInventory(
  signId: string,
  qty: number
): Promise<void> {
  const sign = getSign(signId);
  if (!sign || sign.inventory === null) return; // untracked stock
  const overrides = await readOverrides();
  const current = signId in overrides ? overrides[signId] : sign.inventory;
  overrides[signId] = Math.max(0, current - qty);
  await fs.mkdir(DATA_DIR, { recursive: true });
  await fs.writeFile(INVENTORY_FILE, JSON.stringify(overrides, null, 2));
}

